-- PostgreSQL schema for Only Film (Hibernate naming strategy: camelCase -> snake_case)
CREATE TABLE movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255),
    director VARCHAR(255),
    sinopsis VARCHAR(600),
    active BOOLEAN DEFAULT TRUE,
    duration_minutes INTEGER,
    genre VARCHAR(255),
    image_url VARCHAR(255),
    release_year INTEGER
);

CREATE TABLE salas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    capacity INTEGER NOT NULL,
    screen_type VARCHAR(255) NOT NULL,
    active BOOLEAN DEFAULT TRUE,
    floor_number INTEGER
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL UNIQUE,
    username VARCHAR(255) NOT NULL UNIQUE,
    first_name VARCHAR(50),
    last_name VARCHAR(50),
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    active BOOLEAN,
    image_url VARCHAR(255)
);

CREATE TABLE sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_time TIMESTAMP(6),
    price DOUBLE PRECISION,
    language VARCHAR(255),
    ad_minutes INTEGER,
    active BOOLEAN DEFAULT TRUE,
    movie_id BIGINT REFERENCES movies(id),
    room_id BIGINT REFERENCES salas(id)
);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fila VARCHAR(2),
    seat VARCHAR(3),
    price DOUBLE PRECISION,
    snack_price DOUBLE PRECISION,
    food_price DOUBLE PRECISION,
    discount DOUBLE PRECISION,
    buy_date_time TIMESTAMP(6),
    status VARCHAR(255),
    qr_code VARCHAR(255),
    user_id BIGINT REFERENCES users(id),
    session_id BIGINT REFERENCES sessions(id)
);

CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255),
    description VARCHAR(1000),
    rating INTEGER,
    creation_date TIMESTAMP(6),
    movie_id BIGINT REFERENCES movies(id),
    user_id BIGINT REFERENCES users(id)
);

CREATE INDEX idx_sessions_movie_id ON sessions(movie_id);
CREATE INDEX idx_sessions_room_id ON sessions(room_id);
CREATE INDEX idx_tickets_user_id ON tickets(user_id);
CREATE INDEX idx_tickets_session_id ON tickets(session_id);
CREATE INDEX idx_reviews_movie_id ON reviews(movie_id);
CREATE INDEX idx_reviews_user_id ON reviews(user_id);
